/* There are two types of operator
1.Arithmetic : + - * / %
2.LOgical : && || !
3.Comparison: == === <= >= != !== */


//Arithmetic operator
let x = 20;
let y = 9;
console.log(x - y);
console.log(x + y);
console.log(x * y);
console.log(x / y);
console.log(x % y);

//Comparison
let name = '20';
let age = 20;
console.log(name == age); //just value check
console.log(name === age);//value + data type check
